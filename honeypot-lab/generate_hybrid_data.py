import json
import os

import numpy as np
import pandas as pd


LOG_PATH = (
    "/home/xvhyeri/honeypot-lab/"
    "cowrie-honeypot/var/log/cowrie/cowrie.json"
)

OUTPUT_PATH = "hybrid_training_data.csv"
TOTAL_ROWS = 1000
RANDOM_SEED = 42

# Reproducible dataset generation
rng = np.random.default_rng(RANDOM_SEED)


def extract_real_seed_data():
    """
    Extract behavioural statistics from Cowrie logs.

    Features:
        hits  = total events generated by an IP
        users = number of unique usernames attempted
        cmds  = number of command input events
    """

    ip_stats = {}

    if not os.path.exists(LOG_PATH):
        print(f"[!] Cowrie log file not found: {LOG_PATH}")
        return []

    with open(LOG_PATH, "r", encoding="utf-8") as log_file:
        for line in log_file:
            try:
                event = json.loads(line)
            except (json.JSONDecodeError, TypeError):
                continue

            source_ip = event.get("src_ip")

            if not source_ip:
                continue

            if source_ip not in ip_stats:
                ip_stats[source_ip] = {
                    "hits": 0,
                    "users": set(),
                    "cmds": 0,
                }

            ip_stats[source_ip]["hits"] += 1

            username = event.get("username")
            if username:
                ip_stats[source_ip]["users"].add(username)

            if (
                event.get("eventid") == "cowrie.command.input"
                or event.get("input")
            ):
                ip_stats[source_ip]["cmds"] += 1

    seeds = []

    for stats in ip_stats.values():
        hits = stats["hits"]
        users = len(stats["users"])
        cmds = stats["cmds"]

        # Initial seed interpretation only.
        # This rule is not used to label the final synthetic dataset.
        seed_label = 1 if cmds >= 2 else 0

        seeds.append(
            {
                "hits": hits,
                "users": users,
                "cmds": cmds,
                "label": seed_label,
            }
        )

    return seeds


def clamp(value, minimum, maximum):
    """Keep generated values within reasonable limits."""

    return int(max(minimum, min(round(value), maximum)))


def generate_bot_sample(real_bot_seeds):
    """
    Generate automated or bot-like behaviour.

    Bots commonly produce repeated connections and username attempts.
    Some bots may also execute commands after successfully logging in.
    """

    behaviour_type = rng.choice(
        ["scanner", "bruteforce", "scripted"],
        p=[0.30, 0.45, 0.25],
    )

    if behaviour_type == "scanner":
        hits = rng.normal(45, 22)
        users = rng.normal(2, 1.5)
        cmds = rng.normal(0.5, 1.0)

    elif behaviour_type == "bruteforce":
        hits = rng.normal(105, 35)
        users = rng.normal(11, 5)
        cmds = rng.normal(1.5, 1.8)

    else:
        # A scripted bot may issue several commands.
        hits = rng.normal(75, 28)
        users = rng.normal(4, 2.5)
        cmds = rng.normal(5, 2.8)

    # Occasionally incorporate a real Cowrie seed.
    if real_bot_seeds and rng.random() < 0.30:
        seed = rng.choice(real_bot_seeds)

        hits = 0.55 * hits + 0.45 * seed["hits"]
        users = 0.55 * users + 0.45 * seed["users"]
        cmds = 0.55 * cmds + 0.45 * seed["cmds"]

    return {
        "hits": clamp(hits, 1, 250),
        "users": clamp(users, 1, 40),
        "cmds": clamp(cmds, 0, 25),
        "is_danger": 0,
    }


def generate_human_sample(real_human_seeds):
    """
    Generate interactive human or high-risk behaviour.

    Human-controlled sessions generally execute commands, but short or
    unsuccessful interactive sessions may execute few or no commands.
    """

    behaviour_type = rng.choice(
        ["short_session", "interactive", "advanced"],
        p=[0.25, 0.50, 0.25],
    )

    if behaviour_type == "short_session":
        hits = rng.normal(45, 20)
        users = rng.normal(3, 2)
        cmds = rng.normal(2.5, 2)

    elif behaviour_type == "interactive":
        hits = rng.normal(80, 30)
        users = rng.normal(3, 2)
        cmds = rng.normal(7, 3.5)

    else:
        # Advanced interaction may involve many commands and events.
        hits = rng.normal(115, 38)
        users = rng.normal(5, 3)
        cmds = rng.normal(12, 5)

    # Occasionally incorporate a real Cowrie seed.
    if real_human_seeds and rng.random() < 0.40:
        seed = rng.choice(real_human_seeds)

        hits = 0.50 * hits + 0.50 * seed["hits"]
        users = 0.50 * users + 0.50 * seed["users"]
        cmds = 0.50 * cmds + 0.50 * seed["cmds"]

    return {
        "hits": clamp(hits, 1, 250),
        "users": clamp(users, 1, 40),
        "cmds": clamp(cmds, 0, 25),
        "is_danger": 1,
    }


def introduce_ambiguous_samples(dataset, ambiguity_rate=0.08):
    """
    Introduce realistic uncertainty.

    A small number of bot sessions resemble humans, while some human
    sessions resemble automated activity. Labels remain unchanged because
    these records represent ambiguous but labelled sessions.
    """

    number_to_modify = int(len(dataset) * ambiguity_rate)
    selected_indices = rng.choice(
        len(dataset),
        size=number_to_modify,
        replace=False,
    )

    for index in selected_indices:
        row = dataset[index]

        if row["is_danger"] == 0:
            # Make some bots more interactive.
            row["cmds"] = clamp(
                row["cmds"] + rng.integers(2, 7),
                0,
                25,
            )
            row["users"] = clamp(
                row["users"] - rng.integers(0, 4),
                1,
                40,
            )

        else:
            # Make some human sessions shorter or less interactive.
            row["cmds"] = clamp(
                row["cmds"] - rng.integers(1, 6),
                0,
                25,
            )
            row["users"] = clamp(
                row["users"] + rng.integers(1, 5),
                1,
                40,
            )


def validate_dataset(df):
    """Validate the generated data before saving it."""

    required_columns = {
        "hits",
        "users",
        "cmds",
        "is_danger",
    }

    missing_columns = required_columns.difference(df.columns)

    if missing_columns:
        raise ValueError(
            f"Generated dataset is missing columns: {missing_columns}"
        )

    if df.isnull().any().any():
        raise ValueError("Generated dataset contains missing values.")

    available_classes = set(df["is_danger"].unique())

    if available_classes != {0, 1}:
        raise ValueError(
            f"Both classes are required, but found: {available_classes}"
        )


def main():
    real_seeds = extract_real_seed_data()

    real_bot_seeds = [
        seed for seed in real_seeds
        if seed["label"] == 0
    ]

    real_human_seeds = [
        seed for seed in real_seeds
        if seed["label"] == 1
    ]

    print(f"Real Cowrie seeds      : {len(real_seeds)}")
    print(f"Bot-like seeds         : {len(real_bot_seeds)}")
    print(f"Interactive seeds      : {len(real_human_seeds)}")

    samples_per_class = TOTAL_ROWS // 2
    dataset = []

    for _ in range(samples_per_class):
        dataset.append(
            generate_bot_sample(real_bot_seeds)
        )

    for _ in range(samples_per_class):
        dataset.append(
            generate_human_sample(real_human_seeds)
        )

    # Add overlap between the two behavioural groups.
    introduce_ambiguous_samples(
        dataset,
        ambiguity_rate=0.08,
    )

    df = pd.DataFrame(dataset)

    # Shuffle records so classes are not stored in separate blocks.
    df = df.sample(
        frac=1,
        random_state=RANDOM_SEED,
    ).reset_index(drop=True)

    validate_dataset(df)

    df.to_csv(OUTPUT_PATH, index=False)

    print(f"\nSuccess: '{OUTPUT_PATH}' created.")
    print(f"Total records: {len(df)}")

    print("\nClass distribution:")
    print(df["is_danger"].value_counts().sort_index())

    print("\nFeature statistics by class:")
    print(
        df.groupby("is_danger")[
            ["hits", "users", "cmds"]
        ].mean().round(2)
    )

    print("\nCommand ranges by class:")
    print(
        df.groupby("is_danger")["cmds"].agg(
            ["min", "max", "mean"]
        ).round(2)
    )


if __name__ == "__main__":
    main()
